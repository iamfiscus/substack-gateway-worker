"""Golden outputs of the upstream converters, the correctness bar for the TS port.

Run from the upstream checkout (pinned at bc2e875), with no network:

    cd upstream && uv run python ../scripts/golden/generate.py

Inputs:

- every ``scripts/golden/corpus/*.md`` (Markdown) and
  ``scripts/golden/corpus-docs/*.json`` (ProseMirror docs; inputs harvested from
  test bodies by ``harvest.py``);
- the three draft fixtures in ``packages/gateway_drafts/tests/fixtures``;
- every string (Markdown) and doc-shaped (a ``type: doc`` dict, a single node
  dict with a string ``type``, or a text-node list) value in the
  ``pytest.mark.parametrize`` lists of ``test_dialect_*.py`` and
  ``test_draft_markdown_*.py``.

Outputs, under ``test/fixtures/golden/`` (wiped and rewritten every run). JSON
is ``json.dumps(obj, sort_keys=True, ensure_ascii=False)``, the ``_canon`` of
upstream ``test_draft_round_trip.py``, with no trailing newline:

- ``input/<name>.md``: the Markdown input, byte for byte;
- ``input-doc/<name>.json``: a doc input (canonical JSON);
- ``note/<name>.json``: ``markdown_to_note_payload(md)``, no attachments, for
  inputs of at most ``NOTE_MAX_CHARS`` characters (the note converter's link
  regex is quadratic on runs of ``[``: upstream takes ~17 s on the 100 000-char
  JSON-depth stress inputs, which only matter to the draft parser);
- ``note-error/<name>.json``: ``{"error", "message"}`` when that raises;
- ``draft-doc/<name>.json``: ``markdown_to_draft_doc(md)``;
- ``draft-error/<name>.json``: ``{"error", "message", "line", "str"}`` when that raises;
- ``draft-md/<name>.md``: ``draft_body_to_markdown(json.dumps(doc))`` for each
  draft-doc golden, each doc input and each fixture (``fixture-<stem>``).

``latex_id`` is patched to return ``"GOLDENID00"`` so the output is deterministic.
"""

from __future__ import annotations

import importlib.util
import inspect
import json
import logging
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

from _pytest.mark.structures import ParameterSet

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
UPSTREAM = Path.cwd()
CORPUS = HERE / "corpus"
CORPUS_DOCS = HERE / "corpus-docs"
OUT = ROOT / "test" / "fixtures" / "golden"
DRAFT_TESTS = UPSTREAM / "packages" / "gateway_drafts" / "tests"
FIXTURES = DRAFT_TESTS / "fixtures"
LATEX_ID = "GOLDENID00"
UPSTREAM_COMMIT = "bc2e875"
NOTE_MAX_CHARS = 20_000

README = """\
<!--
MIT License. Copyright (c) 2025 Jakub Slys.
Generated from the converters of https://github.com/jakub-k-slys/substack-gateway-oss
at commit bc2e875. See ../../../LICENSE and ../../../NOTICE.md.
-->
# Golden converter outputs

Generated by `scripts/golden/generate.py`; do not edit. Regenerate with
`cd upstream && uv run python ../scripts/golden/generate.py` (or `npm run golden`).
See the generator's docstring for the layout.
"""


def canon(value: Any) -> str:
    """``_canon`` of upstream ``test_draft_round_trip.py``."""
    return json.dumps(value, sort_keys=True, ensure_ascii=False)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


# --- parametrize lists ----------------------------------------------------------


def _import_test_module(path: Path) -> Any:
    spec = importlib.util.spec_from_file_location(f"golden_{path.stem}", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _test_functions(module: Any) -> list[tuple[str, Any]]:
    found: list[tuple[str, Any]] = []
    for name, obj in vars(module).items():
        if name.startswith("test") and inspect.isfunction(obj):
            found.append((name, obj))
        elif name.startswith("Test") and inspect.isclass(obj):
            for method_name, method in vars(obj).items():
                if method_name.startswith("test") and inspect.isfunction(method):
                    found.append((f"{name}_{method_name}", method))
    return found


def _param_values(func: Any) -> list[Any]:
    values: list[Any] = []
    for mark in getattr(func, "pytestmark", []):
        if mark.name != "parametrize":
            continue
        argnames, argvalues = mark.args[0], mark.args[1]
        if isinstance(argnames, str):
            argnames = [n for n in argnames.replace(" ", "").split(",") if n]
        for entry in argvalues:
            if isinstance(entry, ParameterSet):  # pytest.param(...)
                values.extend(entry.values)
            elif len(argnames) == 1:
                values.append(entry)
            else:
                values.extend(entry)
    return values


def _as_doc(value: Any) -> dict[str, Any] | None:
    """A doc for a doc-shaped parametrize value, else None."""
    if isinstance(value, dict):
        kind = value.get("type")
        if kind == "doc":
            return value
        if isinstance(kind, str):  # a single node: wrap it
            return {"type": "doc", "content": [value]}
        return None
    if (
        isinstance(value, list)
        and value
        and all(isinstance(n, dict) and n.get("type") == "text" for n in value)
    ):
        paragraph = {"type": "paragraph", "attrs": {"textAlign": None}, "content": value}
        return {"type": "doc", "content": [paragraph]}
    return None


def parametrize_inputs() -> tuple[list[tuple[str, str]], list[tuple[str, Any]]]:
    sys.path.insert(0, str(DRAFT_TESTS))  # for ``from _dialect_helpers import ...``
    paths = sorted(
        [*DRAFT_TESTS.glob("test_dialect_*.py"), *DRAFT_TESTS.glob("test_draft_markdown_*.py")]
    )
    markdown: list[tuple[str, str]] = []
    docs: list[tuple[str, Any]] = []
    for path in paths:
        module = _import_test_module(path)
        prefix = re.sub(r"^test_(dialect_|draft_markdown_)", "", path.stem)
        for func_name, func in _test_functions(module):
            base = slug(f"param-{prefix}-{func_name.removeprefix('test_')}")
            md_n = doc_n = 0
            for value in _param_values(func):
                if isinstance(value, str):
                    md_n += 1
                    markdown.append((f"{base}-{md_n:02d}", value))
                elif (doc := _as_doc(value)) is not None:
                    doc_n += 1
                    docs.append((f"{base}-doc-{doc_n:02d}", doc))
    return markdown, docs


# --- running the converters -----------------------------------------------------


def check_upstream() -> None:
    """Fail loudly unless run from the pinned upstream checkout."""
    if not DRAFT_TESTS.is_dir():
        raise SystemExit(f"upstream draft tests not found at {DRAFT_TESTS}; run from upstream/")
    head = subprocess.run(
        ["git", "-C", str(UPSTREAM), "rev-parse", "--short", "HEAD"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    if head != UPSTREAM_COMMIT:
        raise SystemExit(f"upstream is at {head!r}, expected {UPSTREAM_COMMIT!r}")


def main() -> int:
    check_upstream()
    logging.disable(logging.CRITICAL)  # the serializer warns on fallbacks

    from gateway_core.converters.markdown import markdown_to_note_payload
    from gateway_drafts.converters.dialect import fences
    from gateway_drafts.converters.dialect.errors import DraftMarkdownError
    from gateway_drafts.converters.markdown import (
        draft_body_to_markdown,
        markdown_to_draft_doc,
    )

    fences.latex_id = lambda: LATEX_ID

    md_inputs: dict[str, str] = {}
    seen_md: set[str] = set()
    doc_inputs: dict[str, Any] = {}
    seen_docs: set[str] = set()

    def add_md(name: str, md: str) -> None:
        if md not in seen_md and name not in md_inputs:
            seen_md.add(md)
            md_inputs[name] = md

    def add_doc(name: str, doc: Any) -> None:
        try:
            key = json.dumps(doc, sort_keys=True, ensure_ascii=False, allow_nan=False)
        except (TypeError, ValueError):
            return  # not plain JSON
        if key not in seen_docs and name not in doc_inputs:
            seen_docs.add(key)
            doc_inputs[name] = doc

    for path in sorted(CORPUS.glob("*.md")):
        with open(path, encoding="utf-8", newline="") as fh:
            add_md(path.stem, fh.read())
    for path in sorted(CORPUS_DOCS.glob("*.json")):
        add_doc(path.stem, json.loads(path.read_text(encoding="utf-8")))
    param_md, param_docs = parametrize_inputs()
    for name, md in param_md:
        add_md(name, md)
    for name, doc in param_docs:
        add_doc(name, doc)

    if OUT.exists():
        shutil.rmtree(OUT)
    write(OUT / "README.md", README)

    counts = dict.fromkeys(["note", "note-error", "draft-doc", "draft-error", "draft-md"], 0)

    def emit(kind: str, name: str, text: str, ext: str = "json") -> None:
        counts[kind] += 1
        write(OUT / kind / f"{name}.{ext}", text)

    for name in sorted(md_inputs):
        md = md_inputs[name]
        write(OUT / "input" / f"{name}.md", md)
        try:
            if len(md) <= NOTE_MAX_CHARS:
                emit("note", name, canon(markdown_to_note_payload(md)))
        except ValueError as exc:
            emit("note-error", name, canon({"error": type(exc).__name__, "message": str(exc)}))
        try:
            doc = markdown_to_draft_doc(md)
        except DraftMarkdownError as exc:
            error = {
                "error": type(exc).__name__,
                "message": exc.message,
                "line": exc.line,
                "str": str(exc),
            }
            emit("draft-error", name, canon(error))
            continue
        emit("draft-doc", name, canon(doc))
        emit("draft-md", name, draft_body_to_markdown(json.dumps(doc)), "md")

    for name in sorted(doc_inputs):
        doc = doc_inputs[name]
        write(OUT / "input-doc" / f"{name}.json", canon(doc))
        emit("draft-md", f"doc-{name}", draft_body_to_markdown(json.dumps(doc)), "md")

    for path in sorted(FIXTURES.glob("*.json")):
        body = path.read_text(encoding="utf-8")
        emit("draft-md", f"fixture-{path.stem}", draft_body_to_markdown(body), "md")

    summary = ", ".join(f"{count} {kind}" for kind, count in counts.items())
    print(f"{len(md_inputs)} markdown inputs, {len(doc_inputs)} doc inputs: {summary}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
